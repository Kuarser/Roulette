  public void Clear(uint owner)
  {
   if(host.ReadWord(unchecked(owner+0x30))==0)
   {
    host.FaultClear(16,layout.FaultFormat,layout.FaultFile,0xee,layout.FaultFunction);
    throw new InvalidOperationException("Original nonreturning Fault binding returned");
   }
   foreach(var field in Fields)
   {
    uint address=unchecked(owner+field.Offset);
    switch(field.Width){case 0:host.AssignString(address,layout.EmptyCString,0);break;case 1:host.WriteByte(address,(byte)field.Value);break;case 2:host.WriteHalf(address,(ushort)field.Value);break;case 4:host.WriteWord(address,field.Value);break;}
   }
   uint input=host.ReadWord(unchecked(owner+0x30)),remaining=2048;
   if((input&1)!=0){host.WriteByte(input,255);input=unchecked(input+1);remaining=2047;}
   if((input&2)!=0){host.WriteHalf(input,65535);input=unchecked(input+2);remaining-=2;}
   uint words=remaining>>2;
   for(uint i=0;i<words;++i){host.WriteWord(input,uint.MaxValue);input=unchecked(input+4);}
   if((remaining&2)!=0){host.WriteHalf(input,65535);input=unchecked(input+2);}
   if((remaining&1)!=0)host.WriteByte(input,255);
  }
